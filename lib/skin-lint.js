// lib/skin-lint.js — the permanent guard on the skin contract.
//
// Three questions, asked of every HTML page in the repo:
//
//   1. Does a page that CONSUMES a contract token have a skin?
//      A page reading var(--ink) with no skin link renders with the
//      token undefined — silently, as the fallback value. This is the
//      failure the whole system exists to prevent.
//
//   2. Does a page that DEFINES a contract token own its palette?
//      A page that still declares --ink itself is not skinnable: the
//      skin would be overridden by the page. Only pages on the
//      deliberate opt-out list may do this.
//
//   3. Is every skin valid against lib/skin-contract.js?
//      Delegated to lib/skin-tokens.js, which is the contract's
//      enforcer.
//
// Run: node lib/skin-lint.js
// Exits 1 on any error. No dependencies.

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const contract = require('./skin-contract.js');
const { validateSkin, parseRules } = require('./skin-tokens.js');

const REPO = path.resolve(__dirname, '..');
const SKINS_DIR = path.join(REPO, 'assets', 'skins');

/**
 * Pages that are deliberately NOT skinnable, and why.
 *
 * Each one owns a palette that is the work, not the chrome:
 *   - a standalone product with its own design language
 *   - an art piece whose palette IS the piece
 * They keep their inline tokens on purpose. The list is short on
 * purpose: every entry is a claim that re-theming this page would
 * damage it, and it has to be re-argued if it grows.
 */
const UNSKINNABLE = {
    'refael-mp4-maker.html':
        'standalone MP4 product with its own dark design (AGENTS.md sprint 0.18)',
    'sacred-geometry-cymatic.html':
        'generative art piece — the black/gold palette is the artwork',
    'leaf-skeleton.html': 'art piece — paper/ink palette is local',
    'leaf-skeleton-macro.html': 'art piece — paper/ink palette is local',
    'terazije-postcard.html': 'postcard art piece — sepia/flag palette is local',
    'agent-dashboard.html': 'generated by the agent loop; owns no palette',
};

/**
 * Directories git ignores are not served by the repo — they are
 * generated output (mj-output/, logs/, .worktrees/, …). A generated
 * HTML file is not a page the contract applies to, and linting it
 * would make the guard depend on whatever a previous run happened to
 * leave on disk.
 */
function isIgnoredDir(abs) {
    try {
        const r = spawnSync('git', ['check-ignore', '-q', abs], { cwd: REPO, stdio: 'ignore' });
        return r.status === 0;
    } catch {
        return false;
    }
}

/** Every HTML file the repo serves. */
function htmlFiles() {
    const out = [];
    const walk = (dir, depth) => {
        let entries;
        try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
        for (const e of entries) {
            if (e.name.startsWith('.')) continue;
            const abs = path.join(dir, e.name);
            if (e.isDirectory()) {
                if (depth > 0 && !isIgnoredDir(abs)) walk(abs, depth - 1);
            } else if (e.name.endsWith('.html')) {
                out.push(abs);
            }
        }
    };
    walk(REPO, 2);
    return out.sort();
}

/** CSS inside <style> blocks. */
function styleBlocks(html) {
    const out = [];
    const re = /<style\b[^>]*>([\s\S]*?)<\/style>/gi;
    let m;
    while ((m = re.exec(html)) !== null) out.push(m[1]);
    return out;
}

/** Custom properties consumed via var() in a chunk of CSS. */
function usedTokens(css) {
    const out = new Set();
    const re = /var\(\s*(--[A-Za-z0-9_-]+)/g;
    let m;
    while ((m = re.exec(css)) !== null) out.add(m[1].slice(2));
    return out;
}

/**
 * Does this selector define the page's PALETTE (as opposed to deriving
 * a local alias)?
 *
 * A palette scope is one the skin also writes to: :root, html, body,
 * or a [data-theme=…] rule. A definition in any other scope is a
 * derived alias — `.arch-node[data-layer="scanner"] { --node-color:
 * var(--accent-scanner) }` is the page composing a skin token, not
 * overriding it, and is exactly the kind of thing a page should do.
 */
function isPaletteScope(selector) {
    return String(selector)
        .split(',')
        .map((s) => s.trim())
        .some((part) =>
            /^:root\b/i.test(part)
            || /^html\b/i.test(part)
            || /^body\b/i.test(part)
            || /^\[data-theme\s*=/i.test(part)
        );
}

/**
 * Contract tokens a page DEFINES in a palette scope — i.e. the page
 * would override the skin. A skin that is overridden by the page is
 * not a skin.
 */
function paletteOverrides(css, contractSet) {
    const out = new Set();
    const parsed = parseRules(stripCssComments(css));
    for (const rule of parsed.rules) {
        if (!isPaletteScope(rule.selector)) continue;
        for (const decl of rule.declarations) {
            const name = decl.name.startsWith('--') ? decl.name.slice(2) : decl.name;
            if (contractSet.has(name)) out.add(name);
        }
    }
    return out;
}

function stripCssComments(css) {
    return css.replace(/\/\*[\s\S]*?\*\//g, '');
}

function main() {
    const errors = [];
    const notes = [];
    const skinnable = contract.themed.concat(contract.staticTokens);
    const skinnableSet = new Set(skinnable);

    // --- 3. skins ------------------------------------------------------------
    let skins = [];
    try {
        skins = fs.readdirSync(SKINS_DIR).filter((f) => f.endsWith('.css')).sort();
    } catch {
        errors.push({ file: 'assets/skins/', message: 'no skins directory' });
    }
    if (skins.length === 0) {
        errors.push({ file: 'assets/skins/', message: 'no skin files found' });
    }
    for (const f of skins) {
        const abs = path.join(SKINS_DIR, f);
        const expected = path.basename(f, '.css');
        const result = validateSkin(fs.readFileSync(abs, 'utf8'), { expectedName: expected });
        for (const e of result.errors) errors.push({ file: `assets/skins/${f}`, message: e.message });
        for (const w of result.warnings) notes.push({ file: `assets/skins/${f}`, message: w.message });
    }

    // The runtime carries the list of skin names so an unknown ?skin=
    // is never requested. It has to match the directory.
    const known = (require('./skin.js').KNOWN_SKINS || []).slice().sort();
    const onDisk = skins.map((f) => path.basename(f, '.css')).sort();
    for (const name of onDisk) {
        if (!known.includes(name)) {
            errors.push({ file: 'lib/skin.js', message: `skin "${name}" exists but is not in KNOWN_SKINS — an unknown ?skin= would 404` });
        }
    }
    for (const name of known) {
        if (!onDisk.includes(name)) {
            errors.push({ file: 'lib/skin.js', message: `KNOWN_SKINS lists "${name}" but assets/skins/${name}.css does not exist` });
        }
    }

    // --- 1 + 2. pages --------------------------------------------------------
    const pageSummary = { skinned: 0, unskinnable: 0, plain: 0 };
    for (const abs of htmlFiles()) {
        const rel = path.relative(REPO, abs);
        const base = path.basename(abs);
        const html = fs.readFileSync(abs, 'utf8');
        const css = styleBlocks(html).join('\n');

        const used = usedTokens(css);

        const contractUsed = [...used].filter((t) => skinnableSet.has(t));
        const contractDeclared = [...paletteOverrides(css, skinnableSet)];

        const hasLink = /<link\b[^>]*data-skin-stylesheet\b/i.test(html);
        const hasRuntime = /<script\b[^>]*\bsrc=["'][^"']*lib\/skin\.js["']/i.test(html);
        const linkCount = (html.match(/data-skin-stylesheet/g) || []).length;
        const runtimeCount = (html.match(/lib\/skin\.js/g) || []).length;

        const optOut = UNSKINNABLE[base];

        if (optOut) {
            pageSummary.unskinnable++;
            if (hasLink) {
                errors.push({ file: rel, message: `opted out of the skin system but still links a skin (${optOut})` });
            }
            continue;
        }

        // A page that consumes a contract token needs a skin.
        if (contractUsed.length > 0 && !hasLink) {
            errors.push({
                file: rel,
                message: `uses ${contractUsed.length} contract token(s) but loads no skin — the page will render with them undefined`,
            });
            continue;
        }

        if (!hasLink) {
            pageSummary.plain++;
            continue;
        }

        pageSummary.skinned++;

        if (linkCount !== 1) {
            errors.push({ file: rel, message: `expected exactly 1 skin link, found ${linkCount}` });
        }
        if (runtimeCount !== 1) {
            errors.push({ file: rel, message: `expected exactly 1 skin runtime script, found ${runtimeCount}` });
        }
        if (!hasRuntime) {
            errors.push({ file: rel, message: 'skin link without the lib/skin.js runtime — the skin will never switch' });
        }

        // The link must point at a skin that exists.
        const hrefMatch = /<link\b[^>]*data-skin-stylesheet\b[^>]*href=["']([^"']+)["']/i.exec(html)
            || /<link\b[^>]*href=["']([^"']+)["'][^>]*data-skin-stylesheet\b/i.exec(html);
        if (hrefMatch) {
            const target = path.resolve(path.dirname(abs), hrefMatch[1]);
            if (!fs.existsSync(target)) {
                errors.push({ file: rel, message: `skin link points at a missing file: ${hrefMatch[1]}` });
            } else if (path.basename(target) !== 'house.css') {
                notes.push({ file: rel, message: `default skin is ${path.basename(target)}, not house.css` });
            }
        } else {
            errors.push({ file: rel, message: 'skin link has no href' });
        }

        // A skinned page must not define the contract's tokens itself.
        if (contractDeclared.length > 0) {
            errors.push({
                file: rel,
                message: `still defines ${contractDeclared.length} contract token(s) (${contractDeclared.slice(0, 5).join(', ')}${contractDeclared.length > 5 ? ', …' : ''}) — the skin would be overridden by the page`,
            });
        }
    }

    // --- report --------------------------------------------------------------
    for (const n of notes) console.log(`  NOTE  ${n.file}: ${n.message}`);
    for (const e of errors) console.log(`  ERROR ${e.file}: ${e.message}`);

    console.log('');
    console.log(`[skin-lint] skins: ${skins.length ? skins.join(', ') : 'none'}`);
    console.log(`[skin-lint] pages: ${pageSummary.skinned} skinned, ${pageSummary.unskinnable} opted out, ${pageSummary.plain} plain`);
    console.log(`[skin-lint] ${errors.length} error(s), ${notes.length} note(s)`);

    return errors.length === 0 ? 0 : 1;
}

if (require.main === module) {
    process.exit(main());
}

module.exports = { UNSKINNABLE, htmlFiles, main };
